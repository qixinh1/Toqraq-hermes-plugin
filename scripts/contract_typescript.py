from __future__ import annotations

import json
from collections.abc import Mapping
from typing import Any

from .contract_openapi import SCHEMA_METADATA, SCHEMA_REFERENCE

ERROR_JSON_EXTENSION = "x-toqraq-error-json"
TYPE_ONLY_SCHEMA_KEYWORDS = frozenset({ERROR_JSON_EXTENSION})
